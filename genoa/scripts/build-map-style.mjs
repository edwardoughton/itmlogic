// Generate the "Studio Midnight" MapLibre basemap style for Genoa's Live
// Map and write it to src/ui/public-static/styles/genoa.json (served at
// /styles/genoa.json, loaded by MapView, editable in maputnik).
//
// It styles the Protomaps basemap schema (water / land / roads / labels)
// by retoning the package's "dark" theme to the Genoa palette: deep navy
// land + water, steel-blue roads, cream labels.  Amber is deliberately
// NOT used here — it's reserved for the RF data layers (stations, §73.333
// contours, coverage) that MapView adds on top, so they pop.
//
// Run:  node scripts/build-map-style.mjs   (re-run after editing OVERRIDES)

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { layersWithPartialCustomTheme } from 'protomaps-themes-base';

const SOURCE = 'protomaps';

// Studio Midnight — overrides on top of the built-in "dark" theme.
const OVERRIDES = {
  background: '#0a1a25',   // deep navy — the studio backdrop
  earth:      '#11293a',   // landmass, navy slate (sits above the bg)
  water:      '#0a1d2c',   // deeper + bluer than land, so water recedes
  buildings:  '#163448',
  // keep natural areas muted + on-brand (no bright green)
  park_a: '#11302e', park_b: '#11302e',
  wood_a: '#122e2c', wood_b: '#122e2c',
  scrub_a: '#15302c', scrub_b: '#15302c',
  // roads — steel-blue, brighter than land so they read; casings ~bg
  highway: '#41637a', major: '#34506a',
  minor_a: '#294458', minor_b: '#233c50', link: '#34506a', other: '#233c50',
  highway_casing_early: '#0a1620', highway_casing_late: '#0a1620',
  major_casing_early: '#0a1620',   major_casing_late: '#0a1620',
  minor_casing: '#0a1620', link_casing: '#0a1620',
  railway: '#2a4257',
  boundaries: '#3a5066',
  // labels — cream titles, muted blue secondary, deep-navy halos
  city_label: '#ede6d6', city_label_halo: '#06121b',
  state_label: '#9fb3c0', state_label_halo: '#06121b',
  country_label: '#cdd9e2',
  subplace_label: '#b9c6cf', subplace_label_halo: '#06121b',
  roads_label_major: '#aebdc7', roads_label_major_halo: '#0a1620',
  roads_label_minor: '#7d94a3', roads_label_minor_halo: '#0a1620',
  ocean_label: '#5d7e92', waterway_label: '#5d7e92',
  peak_label: '#8aa0ae'
};

const themeLayers = layersWithPartialCustomTheme(SOURCE, 'dark', OVERRIDES, 'en');

// Graceful fallback: a dark raster basemap sits UNDER the Protomaps vector
// layers.  When the self-hosted pmtiles renders, the opaque navy "earth"
// fill covers the raster (you see Studio Midnight).  If the vector source
// ever fails, the raster still shows a dark map — never a black void.
const bgIdx = themeLayers.findIndex(l => l.type === 'background');
const layers = [
  ...themeLayers.slice(0, bgIdx + 1),
  { id: 'raster-fallback', type: 'raster', source: 'carto-dark' },
  ...themeLayers.slice(bgIdx + 1)
];

const style = {
  version: 8,
  name: 'Genoa — Studio Midnight',
  metadata: {
    'genoa:note': 'Generated by scripts/build-map-style.mjs (protomaps-themes-base "dark" retoned to navy+cream). Edit OVERRIDES and re-run, or tweak here in maputnik. Basemap is the self-hosted PMTiles via Genoa\'s /basemap proxy (set BASEMAP_URL); a CARTO dark raster sits underneath as a fallback so the map is never blank. RF data layers (stations/contours/coverage) are added on top in code from the map LAYERS registry.'
  },
  glyphs: 'https://protomaps.github.io/basemaps-assets/fonts/{fontstack}/{range}.pbf',
  sprite: 'https://protomaps.github.io/basemaps-assets/sprites/v4/dark',
  sources: {
    [SOURCE]: {
      type: 'vector',
      url: 'pmtiles://https://genoaiq.com/basemap',
      attribution: '© OpenStreetMap contributors · Protomaps'
    },
    'carto-dark': {
      type: 'raster',
      tiles: [
        'https://a.basemaps.cartocdn.com/dark_all/{z}/{x}/{y}.png',
        'https://b.basemaps.cartocdn.com/dark_all/{z}/{x}/{y}.png',
        'https://c.basemaps.cartocdn.com/dark_all/{z}/{x}/{y}.png'
      ],
      tileSize: 256,
      attribution: '© OpenStreetMap contributors © CARTO'
    }
  },
  layers
};

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/ui/public-static/styles/genoa.json');
writeFileSync(out, JSON.stringify(style, null, 2) + '\n');
console.log(`wrote ${out} · ${layers.length} basemap layers`);
